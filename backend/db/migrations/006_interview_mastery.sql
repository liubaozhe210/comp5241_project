-- Additive Interview Mastery schema. Execute separately against MySQL 8.0.16+.
-- No existing CourseHub table is altered.
create table if not exists im_resumes (
  id char(36) primary key,
  owner_id char(36) not null,
  title varchar(80) not null,
  text longtext not null,
  source_filename varchar(255) null,
  source_mime varchar(100) null,
  source_size_bytes bigint null,
  job_title varchar(120) not null default '',
  seniority varchar(16) not null default 'unspecified',
  job_description text not null,
  created_at datetime(6) not null,
  updated_at datetime(6) not null,
  index ix_im_resumes_owner_created (owner_id, created_at),
  constraint fk_im_resumes_owner foreign key (owner_id) references profiles(id) on delete cascade,
  constraint ck_im_resumes_seniority check (seniority in ('intern', 'junior', 'mid', 'senior', 'unspecified'))
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_0900_ai_ci;

create table if not exists im_assessments (
  id char(36) primary key,
  owner_id char(36) not null,
  resume_id char(36) not null,
  job_title varchar(120) not null default '',
  seniority varchar(16) not null default 'unspecified',
  report_json json not null,
  model varchar(160) not null,
  consent_at datetime(6) not null,
  created_at datetime(6) not null,
  index ix_im_assessments_owner_created (owner_id, created_at),
  index ix_im_assessments_resume (resume_id),
  constraint fk_im_assessments_owner foreign key (owner_id) references profiles(id) on delete cascade,
  constraint fk_im_assessments_resume foreign key (resume_id) references im_resumes(id) on delete cascade,
  constraint ck_im_assessments_seniority check (seniority in ('intern', 'junior', 'mid', 'senior', 'unspecified'))
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_0900_ai_ci;

create table if not exists im_sessions (
  id char(36) primary key,
  owner_id char(36) not null,
  job_title varchar(120) not null default '',
  seniority varchar(16) not null default 'junior',
  interview_type varchar(16) not null default 'mixed',
  status varchar(16) not null default 'in_progress',
  phase varchar(16) not null default 'introduction',
  question_limit int not null,
  asked_count int not null default 0,
  resume_id char(36) null,
  privacy_consent_at datetime(6) not null,
  privacy_policy_version varchar(32) not null default 'v1',
  report_json json null,
  report_error_code varchar(64) null,
  model varchar(160) null,
  current_turn_id char(36) null,
  question_deadline_at datetime(6) null,
  generation_request_id char(36) null,
  end_request_id char(36) null,
  created_at datetime(6) not null,
  updated_at datetime(6) not null,
  index ix_im_sessions_owner_created (owner_id, created_at),
  index ix_im_sessions_resume (resume_id),
  constraint fk_im_sessions_owner foreign key (owner_id) references profiles(id) on delete cascade,
  constraint fk_im_sessions_resume foreign key (resume_id) references im_resumes(id) on delete set null,
  constraint ck_im_sessions_seniority check (seniority in ('intern', 'junior', 'mid', 'senior', 'unspecified')),
  constraint ck_im_sessions_type check (interview_type in ('technical', 'mixed')),
  constraint ck_im_sessions_status check (status in ('in_progress', 'completed', 'abandoned')),
  constraint ck_im_sessions_phase check (phase in ('introduction', 'foundation', 'deep_dive', 'completed')),
  constraint ck_im_sessions_question_limit check (question_limit between 4 and 12),
  constraint ck_im_sessions_asked_count check (asked_count between 0 and question_limit)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_0900_ai_ci;

create table if not exists im_turns (
  id char(36) primary key,
  owner_id char(36) not null,
  session_id char(36) not null,
  question_index int not null,
  phase varchar(16) not null,
  question text not null,
  answer text null,
  feedback varchar(500) not null default '',
  answer_status varchar(16) null,
  score int null,
  strengths json not null,
  improvements json not null,
  evidence json not null,
  review_recommended boolean not null default false,
  question_confirmed_at datetime(6) null,
  request_id char(36) null,
  created_at datetime(6) not null,
  updated_at datetime(6) not null,
  unique key uk_im_turn_question (session_id, question_index),
  unique key uk_im_turn_request (session_id, request_id),
  index ix_im_turns_owner_session (owner_id, session_id),
  constraint fk_im_turns_owner foreign key (owner_id) references profiles(id) on delete cascade,
  constraint fk_im_turns_session foreign key (session_id) references im_sessions(id) on delete cascade,
  constraint ck_im_turns_phase check (phase in ('introduction', 'foundation', 'deep_dive')),
  constraint ck_im_turns_answer_status check (answer_status is null or answer_status in ('answered', 'skipped')),
  constraint ck_im_turns_score check (score is null or score between 0 and 100),
  constraint ck_im_turns_question_index check (question_index between 1 and 12)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_0900_ai_ci;

