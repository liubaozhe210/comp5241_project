def build_pdf(title: str, subtitle: str) -> bytes:
    """生成一个结构正确的最小 PDF（带 xref 偏移），用于演示课件预览。"""

    def esc(text: str) -> str:
        return text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")

    content_lines = [
        "BT",
        "/F1 20 Tf",
        "1 0 0 1 72 760 Tm",
        f"({esc(title)}) Tj",
        "/F1 12 Tf",
        "1 0 0 1 72 726 Tm",
        f"({esc(subtitle)}) Tj",
        "/F1 11 Tf",
        "1 0 0 1 72 690 Tm",
        "(Demo material generated by scripts/seed_demo.py) Tj",
        "ET",
    ]
    content = "\n".join(content_lines).encode("latin-1", "replace")

    bodies = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
    ]

    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for index, body in enumerate(bodies, start=1):
        offsets.append(len(out))
        out += f"{index} 0 obj\n".encode("latin-1") + body + b"\nendobj\n"

    xref_pos = len(out)
    out += f"xref\n0 {len(bodies) + 1}\n".encode("latin-1")
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("latin-1")
    out += (
        f"trailer\n<< /Size {len(bodies) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_pos}\n%%EOF\n"
    ).encode("latin-1")
    return bytes(out)


def main() -> int:
    repo = SupabaseRepo()
    created = {"teacher": 0, "student": 0, "course": 0, "enrollment": 0, "material": 0}
    skipped = {"user": 0, "course": 0, "enrollment": 0, "material": 0}

    print("Probing Supabase ...")
    existing = repo.list_profiles()
    print(f"  existing profiles: {len(existing)}")

    # ---------- 账号 ----------
    profiles: dict[str, dict] = {}
    for login_id, name, email in TEACHERS + STUDENTS:
        role = "teacher" if (login_id, name, email) in TEACHERS else "student"
        found = repo.find_profile(login_id) or repo.find_profile(email)
        if found:
            profiles[login_id] = found
            skipped["user"] += 1
            print(f"  = {role:<7} {login_id:<12} exists ({found['role']})")
            continue
        metadata = {"login_id": login_id, "name": name, "role": role}
        if role == "teacher":
            metadata["invite_code"] = INVITE_CODE
        result = repo.create_auth_user(email, PASSWORD, metadata)
        profile = repo.get_profile(result["id"])
        if not profile:
            print(f"  ! {login_id}: auth user created but profile missing (trigger failed?)")
            return 1
        profiles[login_id] = profile
        created[role] += 1
        print(f"  + {role:<7} {login_id:<12} {email}")

    # ---------- 课程 ----------
    courses: dict[str, dict] = {}
    existing_courses = {c["code"]: c for c in repo.list_courses()}
    for code, name, teacher_login, semester, status, policy, capacity, desc in COURSES:
        if code in existing_courses:
            courses[code] = existing_courses[code]
            skipped["course"] += 1
            print(f"  = course  {code:<9} exists")
            continue
        teacher = profiles.get(teacher_login)
        if not teacher:
            print(f"  ! course {code}: teacher {teacher_login} missing")
            return 1
        row = repo.create_course(
            {
                "code": code,
                "name": name,
                "description": desc,
                "teacher_id": teacher["id"],
                "semester": semester,
                "status": status,
                "enrollment_policy": policy,
                "capacity": capacity,
            }
        )
        courses[code] = row
        created["course"] += 1
        print(f"  + course  {code:<9} {name}")

    # ---------- 选课 ----------
    for code, student_login, status, source in ENROLLMENTS:
        course = courses.get(code)
        student = profiles.get(student_login)
        if not course or not student:
            print(f"  ! enrollment {code}/{student_login}: missing course or student")
            continue
        if repo.get_enrollment(course["id"], student["id"]):
            skipped["enrollment"] += 1
            continue
        decided = status in ("approved", "rejected")
        repo.insert_enrollment(
            {
                "course_id": course["id"],
                "student_id": student["id"],
                "status": status,
                "source": source,
                "decided_at": "2026-10-01T10:00:00+00:00" if decided else None,
                "decided_by": course["teacher_id"] if decided else None,
            }
        )
        created["enrollment"] += 1
        print(f"  + enroll  {code:<9} {student_login:<12} {status}")

    # ---------- 课件 ----------
    for code, title, pages in MATERIALS:
        course = courses.get(code)
        if not course:
            continue
        if any(m["title"] == title for m in repo.list_materials(course["id"])):
            skipped["material"] += 1
            continue
        pdf = build_pdf(title, f"{code} · {course['name']}")
        storage_path = f"{course['id']}/{title.lower().replace(' ', '-').replace('—', '-')}.pdf"
        repo.upload_object(storage_path, pdf, "application/pdf")
        repo.insert_material(
            {
                "course_id": course["id"],
                "title": title,
                "description": "Seeded demo material",
                "storage_path": storage_path,
                "original_name": f"{title}.pdf",
                "size_bytes": len(pdf),
                "mime": "application/pdf",
                "pages": pages,
                "uploader_id": course["teacher_id"],
            }
        )
        created["material"] += 1
        print(f"  + material {code:<9} {title}")

    # ---------- 汇总 ----------
    admins = [p for p in repo.list_profiles() if p["role"] == "admin"]
    print("\nSummary")
    print(f"  created : {created}")
    print(f"  skipped : {skipped}")
    print(f"  admins  : {[a['login_id'] for a in admins] or 'none'}")
    print(f"  password for every seeded account: {PASSWORD}")
    return 0


